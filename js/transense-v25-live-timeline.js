/* V25: decorative translation preview only. No API calls, no account/storage changes. */
(()=>{'use strict';
  const art=document.getElementById('v25LaptopArt');
  const viewport=art?.querySelector('.v25-laptop-screen-window');
  const ui=document.getElementById('v25LaptopScreenUI');
  const sourceEl=document.getElementById('v25-english');
  const caret=document.getElementById('v25-caret');
  const targetEl=document.getElementById('v25-vietnamese');
  const gemini=document.getElementById('v25-gemini');
  const status=document.getElementById('v25-status');
  const button=document.getElementById('v25-demo-button');
  if(!art || !viewport || !ui || !sourceEl || !caret || !targetEl || !gemini || !status || !button) return;
  const english='Technology makes learning more convenient.';
  const vietnamese='Công nghệ giúp việc học trở nên thuận tiện hơn.';
  const duration=12000;
  const reducedMotion=window.matchMedia?.('(prefers-reduced-motion: reduce)').matches||false;
  function resize(){const w=viewport.clientWidth;if(w>0)ui.style.setProperty('--v25-screen-scale',String(w/857));}
  if('ResizeObserver' in window){new ResizeObserver(resize).observe(viewport);} else window.addEventListener('resize',resize,{passive:true});
  resize();
  let elapsed=reducedMotion?9400:0,last=null,visible=true;
  const observer=('IntersectionObserver' in window)?new IntersectionObserver(entries=>{visible=!!entries[0]?.isIntersecting;last=null;},{threshold:0.01}):null;
  observer?.observe(art);
  const render=ms=>{
    const typing=ms<3350, selected=ms>=3350, processing=ms>=4500&&ms<6100, revealing=ms>=6100, done=ms>=8200;
    const count=Math.max(0,Math.min(english.length,Math.floor((ms-340)/64)));
    sourceEl.textContent=english.slice(0,count);
    caret.style.visibility=typing?'visible':'hidden';
    const translatedCount=revealing?Math.max(0,Math.min(vietnamese.length,Math.floor((ms-6250)/36))):0;
    targetEl.textContent=processing?'Đang xử lý bản dịch…':revealing?vietnamese.slice(0,translatedCount):'Bản dịch sẽ xuất hiện tại đây…';
    targetEl.style.color=revealing?'#243d64':'#91a8cb';
    gemini.classList.toggle('v25-selected',selected);
    status.className='v25-live-status'+(done?' v25-success':processing?' v25-working':'');
    status.textContent=processing?'Đang xử lý…':done?'✓ Đã hoàn thành':revealing?'Đang hiển thị kết quả':selected?'Đã chọn Gemini AI':'Nhập văn bản';
    button.className='v25-demo-button'+(processing?' v25-processing':done?' v25-finished':'');
    // Only fixed markup generated by the app; no user-supplied text inserted as HTML.
    button.innerHTML=processing?'<span class="v25-wait-spinner"></span> Đang dịch…':done?'✓ Dịch thành công':'Dịch ngay <span aria-hidden="true">→</span>';
    ui.classList.toggle('v25-loop-reset',ms>11560&&!reducedMotion);
  };
  render(elapsed);
  if(reducedMotion)return;
  function frame(now){if(last===null)last=now;const delta=Math.min(60,now-last);last=now;
    if(visible&&!document.hidden){elapsed=(elapsed+delta)%duration;render(elapsed);}
    window.requestAnimationFrame(frame);
  }
  window.requestAnimationFrame(frame);
})();
